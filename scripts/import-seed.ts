export function buildVerifySql(): string {
  const t = `public.tasks t where t.project_id = ${project}`
  return [
    `select 'projects', count(*)::text from public.projects where legacy_id = ${lit(PROJECT_LEGACY)}`,
    `select 'milestones', count(*)::text from public.milestones where project_id = ${project}`,
    `select 'tasks', count(*)::text from ${t}`,
    `select 'tasks without milestone', string_agg(t.legacy_id, ',' order by t.legacy_id) from ${t} and t.milestone_id is null`,
    `select 'tasks with an assignee', count(*)::text from ${t} and t.assignee_person_id is not null`,
    `select 'tasks with a validator', count(*)::text from ${t} and t.validator_person_id is not null`,
    `select 'tasks committed', count(*)::text from ${t} and t.committed`,
    `select 'tasks with ≥1 step', count(distinct ts.task_id)::text from public.task_steps ts join public.tasks t on t.id = ts.task_id where t.project_id = ${project}`,
    `select 'task_steps rows', count(*)::text from public.task_steps ts join public.tasks t on t.id = ts.task_id where t.project_id = ${project}`,
    `select 'task_deps rows', string_agg(dep.legacy_id || '→' || tk.legacy_id, ',' order by dep.legacy_id || '→' || tk.legacy_id) from public.task_deps d join public.tasks tk on tk.id = d.task_id join public.tasks dep on dep.id = d.depends_on_task_id where d.project_id = ${project}`,
    `select 'asks', count(*)::text from public.asks where project_id = ${project}`,
    `select 'people', count(*)::text from public.people where legacy_id in (${Object.keys(MEMBERSHIP).map(lit).join(', ')})`,
    `select 'project_members', count(*)::text from public.project_members where project_id = ${project}`,
  ].join('\nunion all\n') + ';\n'
}

/** Compares psql output ("check|actual" lines) with EXPECTED; returns the report and whether it passed. */
export function report(output: string): { text: string; ok: boolean } {
  const actual = new Map(
    output
      .trim()
      .split('\n')
      .filter(Boolean)
      .map((l) => {
        const i = l.indexOf('|')
        return [l.slice(0, i), l.slice(i + 1)] as const
      }),
  )
  let ok = true
  const rows = EXPECTED.map(([check, want]) => {
    const have = actual.get(check) ?? '(missing)'
    const pass = have === want
    ok &&= pass
    return `${pass ? 'OK  ' : 'FAIL'}  ${check.padEnd(26)} expected ${want.padEnd(38)} actual ${have}`
  })
  return { text: ['Verification report (BRIEF §7)', ...rows, ok ? 'All counts match.' : 'MISMATCH: import did not reproduce the export.'].join('\n'), ok }
}

function parseArgs(argv: string[]) {
  const opts: ImportOptions & { dbUrl?: string } = { emails: {} }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    const v = argv[i + 1] ?? ''
    if (a === '--owner-email') {
      opts.ownerEmail = v
      i++
    } else if (a === '--db-url') {
      opts.dbUrl = v
      i++
    } else if (a === '--email') {
      const [k, e] = v.split('=')
      if (k && e) opts.emails![k] = e
      i++
    }
  }
  return opts
}

function psql(dbUrl: string, sql: string): string {
  const r = spawnSync('psql', [dbUrl, '-X', '-q', '-t', '-A', '-v', 'ON_ERROR_STOP=1', '-f', '-'], { input: sql, encoding: 'utf8' })
  if (r.status !== 0) throw new Error(r.stderr || `psql exited with ${r.status}`)
  return r.stdout
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, ...rest] = process.argv.slice(2)
  const opts = parseArgs(rest)
  if (cmd === 'sql') process.stdout.write(buildImportSql(readSeed(), opts))
  else if (cmd === 'verify-sql') process.stdout.write(buildVerifySql())
  else if (cmd === 'run') {
    const url = opts.dbUrl ?? process.env.SUPABASE_DB_URL
    if (!url) throw new Error('Pass --db-url or set SUPABASE_DB_URL.')
    psql(url, buildImportSql(readSeed(), opts))
    const r = report(psql(url, buildVerifySql()))
    console.log(r.text)
    process.exit(r.ok ? 0 : 1)
  } else {
    console.error('Usage: node scripts/import-seed.ts sql|verify-sql|run [--db-url …] [--owner-email …] [--email legacy=addr …]')
    process.exit(2)
  }
}
